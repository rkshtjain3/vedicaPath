/**
 * Helper to retrieve allowed relative houses for a given target planet and contributor.
 */
export function getAllowedRelativeHouses(
  targetPlanet: AshtakavargaPlanet,
  contributor: AshtakavargaContributor
): number[] {
  const planetRules = CANONICAL_BINDU_RULES[targetPlanet];
  if (!planetRules) {
    throw new Error(`Invalid target planet for Ashtakavarga: ${targetPlanet}`);
  }
  const houses = planetRules[contributor];
  if (!houses) {
    throw new Error(
      `Invalid contributor for target planet ${targetPlanet}: ${contributor}`
    );
  }
  return houses;
}
